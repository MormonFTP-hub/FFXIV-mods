"""Turn docs/job-versions.md (every job version from 2.0 on, with its community rating) into js/versions.js.

The sim's job window reads it: each job's version history as a rating-coloured timeline, and each playable version's
rating and the reason for it. Run after editing the list:  python BlackMageSim/tools/build_versions.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "job-versions.md"
OUT = ROOT / "js" / "versions.js"

ROLES = {"Tanks": "tank", "Healers": "healer", "Melee DPS": "melee", "Physical ranged": "ranged", "Caster DPS": "caster"}
IDS = {"Paladin": "pld", "Warrior": "war", "Dark Knight": "drk", "Gunbreaker": "gnb", "White Mage": "whm", "Scholar": "sch",
       "Astrologian": "ast", "Sage": "sge", "Monk": "mnk", "Dragoon": "drg", "Ninja": "nin", "Samurai": "sam", "Reaper": "rpr",
       "Viper": "vpr", "Bard": "brd", "Machinist": "mch", "Dancer": "dnc", "Black Mage": "blm", "Summoner": "smn",
       "Red Mage": "rdm", "Pictomancer": "pct", "Blue Mage": "blu"}
ITEM = re.compile(r"^\d+\. (.+?) \((\d{4}-\d{2}-\d{2}) → (present|\d{4}-\d{2}-\d{2})\)(.*?): (.*?) \*\*Rating (\d)/5:\*\* (.*)$")


def main():
    jobs, order, role, job = {}, [], None, None
    for line in DOC.read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            role = next((v for k, v in ROLES.items() if line[3:].startswith(k)), None)
        elif line.startswith("### ") and role:
            name = re.sub(r"\s*\((from|limited).*?\)", "", line[4:])
            name, _, alias = name.partition(" / ")
            jid = IDS[name]
            job = jobs[jid] = {"name": name, "alias": alias, "role": "limited" if jid == "blu" else role, "versions": []}
            order.append(jid)
        elif job is not None and (m := ITEM.match(line)):
            label, start, end, extra, notes, rating, why = m.groups()
            job["versions"].append({
                "label": re.sub(r"\s*\(minor[^)]*\)", "", label).strip(),
                "start": start, "end": None if end == "present" else end,
                "minor": "(minor" in extra or "(minor" in label,
                "notes": notes.replace("← built", "").strip(),
                "rating": int(rating), "why": why.strip(),
            })
    n = sum(len(j["versions"]) for j in jobs.values())
    js = ("// Generated by tools/build_versions.py from docs/job-versions.md: every job's versions from 2.0 on, each with a\n"
          "// 1-5 rating for how players remember it (5 most missed, 4 well liked, 3 mixed, 2 unpopular, 1 panned).\n"
          "window.BLM = window.BLM || {};\nBLM.JOB_HISTORY = " + json.dumps({k: jobs[k] for k in order}, ensure_ascii=False, indent=0) + ";\n")
    OUT.write_text(js, encoding="utf-8")
    print(f"{len(jobs)} jobs, {n} versions -> {OUT} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
