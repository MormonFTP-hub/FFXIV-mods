"""The game's own sounds and music for the sim, from your FFXIV install (like its models, icons and maps).

Sounds: every action the sim's jobs have (the Action rows in tools/extract_icons.py) plays the sounds its animation
timelines name: the cast's (AnimationStart, through ActionCastTimeline), the action's own (AnimationEnd) and the
hit's (ActionTimelineHit). A timeline (.tmb) lists them as C063 entries: the sound bank (.scd), which sound in it,
and the frame (30 a second) it starts on. Each boss in a fight (tools/export_map.py's zones) gets the same for its
abilities, found from the ability ids in the fight's cactbot timeline. Voices are left out.

Music: each fight's own (InstanceContent's BGM, reached from the zone's TerritoryType through ContentFinderCondition)
and the victory fanfare (its WinBGM), with the game's loop points. A track the game plays in parts (music/.../timeline/,
M5S's dance floor) is kept as its parts in order.

  python -P -E BlackMageSim/tools/export_audio.py        # needs ffmpeg on PATH (it encodes MP3, which every browser plays)

Writes (git-ignored; the page loads the files it needs when it needs them, and the build copies them beside it):
  work/sounds/<job>.js       a job's action sounds: {clips: {id: data URL}, actions: {"job:key": {cast, use, hit}}},
                             each of cast/use/hit a list of [clip, second after the action starts]
  work/sounds/boss-<key>.js  a fight's boss: {clips, bosses: {key: {ability name: {cast, use}}}}
  work/music/<key>.js        a fight's music: {key, parts: [{src, loop: [start, end] seconds or null}]}
  work/music/win.js          the victory fanfare
Each pushes its data onto BLM.SOUNDS_IN or BLM.MUSIC_IN, where js/audio.js takes it. The MP3s are kept in
work/audio-cache/, so a run after adding a fight only encodes what's new.
"""
import base64
import hashlib
import json
import re
import struct
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import export_map as M                        # noqa: E402  (its zones; it also sets up PMP Viewer's path)
import scd                                    # noqa: E402
from export_models import game                # noqa: E402
from extract_icons import JOBS, Sheet, name_col  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "work"
CACHE = OUT / "audio-cache"
HEADER = "// Generated by tools/export_audio.py from your FFXIV install. FINAL FANTASY XIV (c) SQUARE ENIX.\n"

# Action's columns: AnimationStart (an ActionCastTimeline row), AnimationEnd and ActionTimelineHit (ActionTimeline rows).
START, END, HIT = 5, 7, 8


def tmb_sounds(key, skl=None):
    """The sounds a timeline plays: [(bank path, sound index, second)], voices left out."""
    if not key:
        return []
    if "[SKL_ID]" in key:
        if not skl:
            return []
        key = key.replace("[SKL_ID]", skl)
    local = game.game_file(f"chara/action/{key}.tmb")
    if not local:
        return []
    b = open(local, "rb").read()
    out = []
    for m in re.finditer(rb"C063", b):
        o = m.start()
        if o + 0x20 > len(b):
            continue
        frame = struct.unpack_from("<H", b, o + 10)[0]
        off, index = struct.unpack_from("<iI", b, o + 20)
        s = o + 8 + off
        if not (0 < s < len(b)) or not b.startswith(b"sound/", s):
            continue
        path = b[s:b.index(b"\0", s)].decode("ascii", "replace")
        if "/voice/" in path.lower():
            continue
        out.append((path, index, round(frame / 30, 3)))
    return out


class Clips:
    """Each (bank, index) once, as an MP3 data URL."""

    def __init__(self):
        self.urls, self.ids, self.banks, self.missing = {}, {}, {}, set()

    def get(self, path, index):
        k = (path.lower(), index)
        if k in self.ids:
            return self.ids[k]
        if path.lower() not in self.banks:
            local = game.game_file(path)
            try:
                self.banks[path.lower()] = scd.sounds(open(local, "rb").read()) if local else []
            except Exception as e:          # noqa: BLE001  (a bank this reader can't take)
                print(f"  {path}: {e}")
                self.banks[path.lower()] = []
        bank = self.banks[path.lower()]
        if not bank:
            self.missing.add(path)
            self.ids[k] = None
            return None
        cid = hashlib.sha1(f"{path.lower()}#{index}".encode()).hexdigest()[:10]
        cached = CACHE / f"{cid}.mp3"
        if not cached.exists():
            CACHE.mkdir(parents=True, exist_ok=True)
            cached.write_bytes(encode(bank[min(index, len(bank) - 1)]["bytes"], sfx=True))
        self.urls[cid] = "data:audio/mpeg;base64," + base64.b64encode(cached.read_bytes()).decode()
        self.ids[k] = cid
        return cid

    def pick(self, ids):
        return {c: self.urls[c] for c in sorted(ids)}

    def list(self, sounds):
        out = []
        for path, index, t in sounds:
            c = self.get(path, index)
            if c and [c, t] not in out:
                out.append([c, t])
        return out


def encode(data, sfx):
    """Ogg or WAV bytes to MP3: sound effects mono at 48 kbps with the silence after them cut, music 96 kbps."""
    args = ["ffmpeg", "-hide_banner", "-loglevel", "error", "-i", "pipe:0"]
    if sfx:
        args += ["-af", "areverse,silenceremove=start_periods=1:start_threshold=-60dB,areverse", "-ac", "1", "-b:a", "48k"]
    else:
        args += ["-b:a", "96k"]
    args += ["-ar", "44100", "-f", "mp3", "pipe:1"]
    return subprocess.run(args, input=data, capture_output=True, check=True).stdout


def loop_points(snd):
    """The loop as seconds [start, end], from the Ogg's LoopStart/LoopEnd comments (samples), else none."""
    a = re.search(rb"LoopStart=(\d+)", snd["bytes"][:8192])
    b = re.search(rb"LoopEnd=(\d+)", snd["bytes"][:8192])
    if not (a and b):
        return None
    return [round(int(a.group(1)) / snd["rate"], 4), round(int(b.group(1)) / snd["rate"], 4)]


def action_sounds(clips):
    action, cast_tl, tl = Sheet("Action"), Sheet("ActionCastTimeline"), Sheet("ActionTimeline")
    kcol = tl.string_cols()[0]
    key = (lambda r: tl.value(r, kcol) if r and r in tl.rows() else "")
    assert key(action.value(3577, END)) == "magic/thm_black/mgc002", "Action's AnimationEnd column moved"
    out = {}
    for job, cfg in JOBS.items():
        for k, (rid, _) in cfg["actions"].items():
            if rid not in action.rows():
                continue
            st = action.value(rid, START)
            ck = key(cast_tl.value(st, 0)) if st and st in cast_tl.rows() else ""
            cast = tmb_sounds(ck) + (tmb_sounds(ck.replace("_start", "_loop")) if ck.endswith("_start") else [])
            got = {"cast": clips.list(cast), "use": clips.list(tmb_sounds(key(action.value(rid, END)))),
                   "hit": clips.list(tmb_sounds(key(action.value(rid, HIT))))}
            got = {n: v for n, v in got.items() if v}
            if got:
                out[f"{job}:{k}"] = got
        print(f"{job}: {sum(1 for x in out if x.startswith(job + ':'))} of {len(cfg['actions'])} actions have sounds")
    return out


def boss_sounds(clips):
    """Per fight, its boss's abilities (by the Action sheet's name, as the timeline shows them) and their sounds."""
    action, cast_tl, tl = Sheet("Action"), Sheet("ActionCastTimeline"), Sheet("ActionTimeline")
    kcol = tl.string_cols()[0]
    ncol = name_col(action, 141, "Fire")
    key = (lambda r: tl.value(r, kcol) if r and r in tl.rows() else "")
    out = {}
    for zk, z in M.ZONES.items():
        f = z.get("fight")
        if not f or not f.get("model"):
            continue
        cache = OUT / "timelines" / (f["timeline"].replace("/", "_") + ".txt")
        if not cache.exists():
            print(f"{zk}: no cached timeline (export the map or --timeline first)")
            continue
        md = f["model"]
        skl = f"{'m' if md.get('kind', 'monster') == 'monster' else 'd'}{md['id']:04d}"
        ids = set()
        for line in cache.read_text(encoding="utf-8").splitlines():
            m = re.match(r'^(\d+(?:\.\d+)?)\s+"([^"]+)"(.*)$', line)
            if m and "id:" in m.group(3):
                ids.update(int(x, 16) for x in re.findall(r'"([0-9A-Fa-f]{3,5})"', m.group(3).split("}")[0]))
        abil = {}
        for rid in sorted(ids):
            if rid not in action.rows():
                continue
            name = action.value(rid, ncol)
            st = action.value(rid, START)
            ck = key(cast_tl.value(st, 0)) if st and st in cast_tl.rows() else ""
            cast = clips.list(tmb_sounds(ck, skl))
            use = clips.list(tmb_sounds(key(action.value(rid, END)), skl) + tmb_sounds(key(action.value(rid, HIT)), skl))
            if not (cast or use) or not name:
                continue
            a = abil.setdefault(name, {})
            for n, v in (("cast", cast), ("use", use)):
                for c in v:
                    if c not in a.setdefault(n, []):
                        a[n].append(c)
        out[zk] = {n: {k: v for k, v in a.items() if v} for n, a in abil.items()}
        print(f"{zk}: {len(out[zk])} abilities with sounds ({len(ids)} ids in the timeline)")
    return out


def music():
    T, C, I, B = Sheet("TerritoryType"), Sheet("ContentFinderCondition"), Sheet("InstanceContent"), Sheet("BGM")
    bgm_path = (lambda r: B.value(r, 0) if r in B.rows() else "")
    ic_bgm = {I.value(r, 4) for r in I.rows()}
    win = None
    for zk, z in M.ZONES.items():
        if z.get("music"):                        # a zone's own pick (the pier: its field music)
            paths = [z["music"]]
        elif not z.get("fight"):
            continue
        else:
            paths = None
        if paths is None:
            paths = fight_music(zk, z, T, C, I, bgm_path, ic_bgm)
            if not paths:
                continue
            w = paths.pop()
            win = win or w
        parts = []
        for p in paths:
            for snd in scd.sounds(open(game.game_file(p), "rb").read())[:1]:
                loop = loop_points(snd)
                if len(paths) > 1 and not loop:   # a part that doesn't loop: the ending, not played in the fight
                    continue
                parts.append({"src": "data:audio/mpeg;base64," + base64.b64encode(music_mp3(p, snd)).decode(),
                              "loop": loop, "file": p.split("/")[-1]})
        js = push("MUSIC_IN", {"key": zk, "parts": parts})
        (OUT / "music" / f"{zk}.js").write_text(js, encoding="utf-8")
        print(f"{zk}: music {', '.join(x['file'] for x in parts)}  {len(js) / 1024 / 1024:.1f} MB")
    if win and bgm_path(win):
        p = bgm_path(win)
        snd = scd.sounds(open(game.game_file(p), "rb").read())[0]
        part = {"src": "data:audio/mpeg;base64," + base64.b64encode(music_mp3(p, snd)).decode(),
                "loop": loop_points(snd), "file": p.split("/")[-1]}
        js = push("MUSIC_IN", {"key": "win", "parts": [part]})
        (OUT / "music" / "win.js").write_text(js, encoding="utf-8")
        print(f"victory fanfare {part['file']}  {len(js) / 1024:.0f} KB")


def fight_music(zk, z, T, C, I, bgm_path, ic_bgm):
    """A fight's music files (its parts in order) and, last, its victory fanfare's BGM row; None when there's none."""
    B = Sheet("BGM")
    bg = z["bg"].removeprefix("bg/").rstrip("/") + "/"
    rows = [r for r in sorted(T.rows()) if str(T.value(r, 1)).startswith(bg) and T.value(r, 10)]
    found = None
    for r in reversed(rows):                      # the last one: the Savage version, after the normal one
        try:
            ic = C.value(T.value(r, 10), 3)
            found = (I.value(ic, 4), I.value(ic, 5))
            if bgm_path(found[0]):
                break
        except Exception:                         # noqa: BLE001  (a content row of another kind)
            found = None
    if not found:
        print(f"{zk}: no music found")
        return None
    bgm, win_row = found
    paths = [bgm_path(bgm)]
    if "/timeline/" in paths[0].lower():          # a track in parts: the numbers after it, up to another fight's
        stem = (lambda p: re.sub(r"\d+\.scd$", "", p.lower()))
        num = (lambda p: int(re.search(r"(\d+)\.scd$", p).group(1)))
        same = {num(bgm_path(x)): bgm_path(x) for x in B.rows()
                if stem(bgm_path(x)) == stem(paths[0]) and (x == bgm or x not in ic_bgm)}
        n = num(paths[0]) + 1
        while n in same:
            paths.append(same[n])
            n += 1
    return paths + [win_row]


def music_mp3(path, snd):
    cached = CACHE / (hashlib.sha1(path.lower().encode()).hexdigest()[:10] + "-music.mp3")
    if not cached.exists():
        CACHE.mkdir(parents=True, exist_ok=True)
        cached.write_bytes(encode(snd["bytes"], sfx=False))
    return cached.read_bytes()


def push(queue, obj):
    return (HEADER + "window.BLM = window.BLM || {};\n"
            f"(BLM.{queue} = BLM.{queue} || []).push(" + json.dumps(obj, separators=(",", ":")) + ");\n")


def used(d):
    """The clip ids in {name: {cast/use/hit: [[clip, t]]}}."""
    return {c for v in d.values() for lst in v.values() for c, _ in lst}


def main():
    clips = Clips()
    actions = action_sounds(clips)
    bosses = boss_sounds(clips)
    for d in ("sounds", "music"):
        (OUT / d).mkdir(exist_ok=True)
    total = 0
    for job in JOBS:
        mine = {k: v for k, v in actions.items() if k.startswith(job + ":")}
        js = push("SOUNDS_IN", {"name": job, "clips": clips.pick(used(mine)), "actions": mine})
        (OUT / "sounds" / f"{job}.js").write_text(js, encoding="utf-8")
        total += len(js)
    for zk, abil in bosses.items():
        js = push("SOUNDS_IN", {"name": f"boss-{zk}", "clips": clips.pick(used(abil)), "bosses": {zk: abil}})
        (OUT / "sounds" / f"boss-{zk}.js").write_text(js, encoding="utf-8")
        total += len(js)
    print(f"{len(clips.urls)} sounds, {total / 1024 / 1024:.1f} MB in {OUT / 'sounds'}")
    if clips.missing:
        print(f"  {len(clips.missing)} banks missing or unreadable, e.g. {sorted(clips.missing)[:5]}")
    if "--no-music" not in sys.argv:
        music()


if __name__ == "__main__":
    try:
        main()
    finally:
        game.SERVE.close()
