"""Bundle the converted models and nav data into work/game-assets.js so index.html runs from disk.

Opened over http the game fetches work/models/*.glb directly; opened as a file (file://) the browser
blocks fetch, so it loads this script instead. Run after export_heroes.py, export_map.py and
build_nav.py:

    python GoatsSim/tools/pack_assets.py
"""
import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WORK = ROOT / "work"
MODELS = ["hanamura", "reinhardt", "zarya", "dva_mech", "dva_pilot", "lucio", "brigitte", "zenyatta",
          "hammer", "cannon", "amp", "flail", "shield", "lightgun"]


def main():
    pack = {}
    for name in MODELS:
        p = WORK / "models" / f"{name}.glb"
        pack[name] = base64.b64encode(p.read_bytes()).decode("ascii")
    pack["nav_meta"] = json.loads((WORK / "map" / "nav.json").read_text(encoding="utf-8"))
    pack["nav_bin"] = base64.b64encode((WORK / "map" / "nav.bin").read_bytes()).decode("ascii")
    out = WORK / "game-assets.js"
    with out.open("w", encoding="utf-8") as fp:
        fp.write("// Generated by tools/pack_assets.py from the Overwatch rips in source/. Overwatch (c) Blizzard Entertainment.\n")
        fp.write("window.G = window.G || {};\nG.PACK = ")
        json.dump(pack, fp, separators=(",", ":"))
        fp.write(";\n")
    print(f"wrote {out} ({out.stat().st_size / 1048576:.1f} MB)")


if __name__ == "__main__":
    main()
